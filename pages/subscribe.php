<?php
// Simple subscribe handler: sends email using basic mail() with From set from smtp_settings.from_email when available.
require_once __DIR__ . '/../inc/functions.php';
try { require_once __DIR__ . '/../admin/includes/db.php'; } catch (Exception $e) {}

// CSRF protection
if (session_status() !== PHP_SESSION_ACTIVE) { session_start(); }
if (empty($_SESSION['csrf_token'])) {
    try { $_SESSION['csrf_token'] = bin2hex(random_bytes(32)); }
    catch (Exception $e) { $_SESSION['csrf_token'] = sha1(uniqid('', true)); }
}

$success = false;
$message = t('invalid_email');
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!isset($_POST['csrf_token']) || !hash_equals($_SESSION['csrf_token'] ?? '', $_POST['csrf_token'])) {
        $success = false;
        $message = t('invalid_csrf');
    } else {
    $email = trim($_POST['email'] ?? '');
    if (filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $to = null;
        $cc = [];
        $smtp = null;
        if (isset($pdo)) {
            $c = $pdo->query("SELECT email, email1 FROM company_info_common LIMIT 1")->fetch();
            if ($c) {
                $to = $c['email'] ?? null;
                if (!empty($c['email1'])) $cc[] = $c['email1'];
            }
            $smtp = $pdo->query("SELECT * FROM smtp_settings LIMIT 1")->fetch();
        }

        if (!$to) {
            $message = t('recipient_address_not_configured');
        } else {
            $subject = t('news');
            $body = "New subscription from: " . $email . "\n\n---\nThis message was generated by the site subscribe form.";

            $sent = false;
            // Try PHPMailer (composer) if available
            $composerAutoload = __DIR__ . '/../vendor/autoload.php';
            if (file_exists($composerAutoload)) {
                require_once $composerAutoload;
                if (class_exists('PHPMailer\\PHPMailer\\PHPMailer')) {
                    try {
                        $mail = new \PHPMailer\PHPMailer\PHPMailer(true);
                        if ($smtp && (!empty($smtp['is_active']))) {
                            $mail->isSMTP();
                            $mail->Host = $smtp['smtp_host'] ?? 'localhost';
                            $mail->SMTPAuth = !empty($smtp['smtp_username']);
                            $mail->Username = $smtp['smtp_username'] ?? '';
                            $mail->Password = $smtp['smtp_password'] ?? '';
                            $enc = ($smtp['smtp_encryption'] ?? 'tls');
                            if (strtolower($enc) === 'ssl') {
                                $mail->SMTPSecure = \PHPMailer\PHPMailer\PHPMailer::ENCRYPTION_SMTPS;
                            } else {
                                $mail->SMTPSecure = \PHPMailer\PHPMailer\PHPMailer::ENCRYPTION_STARTTLS;
                            }
                            $mail->Port = (int)($smtp['smtp_port'] ?? 587);
                        }
                        $fromEmail = $smtp['from_email'] ?? ('webmaster@' . ($_SERVER['SERVER_NAME'] ?? 'localhost'));
                        $fromName = $smtp['from_name'] ?? $fromEmail;
                        $mail->setFrom($fromEmail, $fromName);
                        $mail->addAddress($to);
                        foreach ($cc as $cEmail) $mail->addCC($cEmail);
                        $mail->Subject = $subject;
                        $mail->Body = $body;
                        $mail->send();
                        $sent = true;
                    } catch (Exception $e) {
                        $sent = false;
                        error_log('Subscription delivery failed: '.$e->getMessage());
                        $message = t('email_send_failed');
                    }
                }
            }

            if (!$sent) {
                // fallback to mail()
                $headers = [];
                if (!empty($smtp['from_email'] ?? '')) $headers[] = 'From: ' . ($smtp['from_name'] ?? $smtp['from_email']) . ' <' . $smtp['from_email'] . '>';
                else $headers[] = 'From: webmaster@' . ($_SERVER['SERVER_NAME'] ?? 'localhost');
                if (!empty($cc)) $headers[] = 'Cc: ' . implode(',', $cc);
                $ok = @mail($to, $subject, $body, implode("\r\n", $headers));
                if ($ok) {
                    $success = true;
                    $message = t('email_sent_success');
                } else {
                    if (empty($message)) $message = t('email_send_failed');
                }
            } else {
                $success = true;
                $message = t('email_sent_success');
            }
        }
    } else {
        $message = t('invalid_email');
    }
    }
}

?><?php page_intro(ui('newsletter'),t('news'),ui('newsletter_desc')); ?>
<section class="h-shell p-subscribe"><?php if($_SERVER['REQUEST_METHOD']==='POST'): ?><div class="p-notice<?= $success?'':' p-notice-error' ?>" role="<?= $success?'status':'alert' ?>"><?= e($message) ?></div><?php endif; ?>
<?php if(!$success): ?><form method="post" action="index.php?page=subscribe"><input type="hidden" name="csrf_token" value="<?= e($_SESSION['csrf_token']) ?>"><div class="p-field"><label for="subscribe-email"><?= e(t('email')) ?> *</label><input id="subscribe-email" name="email" type="email" autocomplete="email" value="<?= e($_POST['email'] ?? '') ?>" required></div><button class="h-button p-form-submit" type="submit"><?= e(t('subscribe')) ?><span class="h-button-arrow">↗</span></button></form><?php endif; ?></section>
